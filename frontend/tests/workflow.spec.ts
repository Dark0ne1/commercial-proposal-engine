import { test, expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
test("API proxy enforces the JSON body limit", async ({request}) => {
  const response = await request.post("/api/login", {data:{email:"manager@example.test",password:"x".repeat(300000)}});
  expect(response.status()).toBe(413);
  const health = await request.get("/api/health");
  expect((await health.json()).mode).toBe("mock");
});
test("manager creates, revises, confirms and downloads a real proposal", async ({page}) => {
  await page.goto("/");
  await page.getByLabel("Пароль", {exact:true}).fill(process.env.DEMO_PASSWORD || "demo-password-123");
  await page.getByRole("button", {name:"Войти в систему"}).click();
  await expect(page.getByRole("heading", {name:"Новая заявка"})).toBeVisible();
  await page.getByLabel("Компания").selectOption("2");
  await page.getByLabel("Обращение клиента").fill("Просим 2 шт. SKU-0001. Автотест UI.");
  await page.getByRole("button", {name:"Зарегистрировать заявку"}).click();
  await expect(page.getByRole("heading", {name:"Позиции и условия"})).toBeVisible();
  await page.getByLabel("Поиск по каталогу").fill("SKU-0001");
  await page.locator(".catalog-item").click();
  await page.getByLabel("Количество 1", {exact:true}).fill("2");
  await page.getByRole("button", {name:"Рассчитать и сохранить версию"}).click();
  await expect(page.getByRole("button", {name:"Подтвердить цены"})).toBeEnabled();
  await page.getByLabel("Комментарий менеджера").fill("Проверено менеджером в браузере");
  await expect(page.getByRole("button", {name:"Подтвердить цены"})).toBeDisabled();
  await page.getByRole("button", {name:"Рассчитать и сохранить версию"}).click();
  await page.getByRole("button", {name:"Подтвердить цены"}).click();
  await expect(page.getByRole("link", {name:"Скачать PDF"})).toBeVisible({timeout:100000});
  const pdfUrl = await page.getByRole("link", {name:"Скачать PDF"}).getAttribute("href");
  const docxUrl = await page.getByRole("link", {name:"Скачать DOCX"}).getAttribute("href");
  const pdf = await page.request.get(pdfUrl!);
  const docx = await page.request.get(docxUrl!);
  expect(pdf.status()).toBe(200); expect((await pdf.body()).subarray(0,4).toString()).toBe("%PDF");
  expect(docx.status()).toBe(200); expect((await docx.body()).subarray(0,2).toString()).toBe("PK");
  await mkdir("../output", {recursive:true});
  await writeFile("../output/proposal-example.pdf", await pdf.body());
  await writeFile("../output/proposal-example.docx", await docx.body());
  await expect(page.getByText("Менеджер подтвердил КП", {exact:true})).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:"../output/ui-desktop.png", fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole("heading", {name:"Предложение клиенту"})).toBeVisible();
  const overflow = await page.evaluate(() => [...document.querySelectorAll("body *")].filter(el => el.getBoundingClientRect().right > innerWidth + 1).map(el => ({tag:el.tagName, cls:el.className, right:el.getBoundingClientRect().right})).slice(0,15));
  expect(await page.evaluate(() => document.documentElement.scrollWidth), JSON.stringify(overflow)).toBeLessThanOrEqual(390);
  await page.screenshot({path:"../output/ui-mobile.png", fullPage:true});
});
